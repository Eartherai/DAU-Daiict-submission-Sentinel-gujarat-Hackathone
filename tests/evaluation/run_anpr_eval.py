#!/usr/bin/env python3
"""Measure ANPR yield per camera against ground truth.

This produces the numbers that drive Camera Capability Grading. Nothing here is
tuned to flatter the result: ground truth is generated by the scene renderer and
is never edited, and a camera that yields nothing is reported as yielding
nothing.

Output is both human-readable and machine-readable (var/logs/anpr_eval.json).

Run:  python tests/evaluation/run_anpr_eval.py [--fps 5]
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from collections import defaultdict
from pathlib import Path

import av

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from saakshya.analytics.anpr import AnprConfig, AnprEngine, PlateVoter
from saakshya.analytics.plates import parse


def decode_sampled(clip: Path, target_fps: float):
    """Decode at a reduced rate, driven by PTS — never by frame count."""
    c = av.open(str(clip))
    s = next(x for x in c.streams if x.type == "video")
    tb = float(s.time_base)
    step = 1.0 / target_fps
    nxt = 0.0
    for f in c.decode(s):
        if f.pts is None:
            continue
        t = float(f.pts) * tb
        if t + 1e-6 < nxt:
            continue
        nxt = t + step
        yield t, f.to_ndarray(format="bgr24")
    c.close()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fps", type=float, default=5.0, help="analytics sampling rate")
    ap.add_argument("--out", default="var/logs/anpr_eval.json")
    args = ap.parse_args()

    gt = json.loads((ROOT / "tests" / "evaluation" / "ground_truth.json").read_text())
    cat = json.loads((ROOT / "var" / "media" / "catalogue.json").read_text())
    cams = {c["id"]: c for c in cat["cameras"]}

    truth_by_cam: dict[str, set[str]] = defaultdict(set)
    for o in gt["observations"]:
        truth_by_cam[o["camera_id"]].add(o["plate"])

    engine = AnprEngine(AnprConfig())
    results: dict[str, dict] = {}

    print(f"ANPR evaluation — sampling at {args.fps} fps")
    print(f"engine: {engine.version}\n")
    print(f"{'camera':<9}{'dept':<16}{'res':<11}{'frm':>5}{'det':>5}{'ok':>5}"
          f"{'rec':>7}  {'plates found':<34}{'ms/frm':>7}")
    print("-" * 104)

    for cid in sorted(cams):
        clip = ROOT / "var" / "media" / f"{cid}.mp4"
        if not clip.exists():
            continue
        voter = PlateVoter(AnprConfig())
        frames = detections = 0
        t0 = time.perf_counter()
        for pts, img in decode_sampled(clip, args.fps):
            frames += 1
            reads = engine.read_frame(img, pts)
            detections += len(reads)
            # One bucket per camera: this stage has no tracker yet, so voting is
            # over the whole pass rather than per track. Understating, not
            # overstating, what the pipeline currently does.
            voter.add(cid, reads)
        elapsed = time.perf_counter() - t0

        all_voted = voter.resolve_all(cid)
        voted = all_voted[0] if all_voted else None
        raw_valid = sum(1 for r in voter._reads[cid] if parse(r.text).valid)
        found = {v.plate.canonical for v in all_voted}
        expected = truth_by_cam.get(cid, set())

        results[cid] = {
            "department": cams[cid]["department"],
            "resolution": f"{cams[cid]['properties']['width']}x{cams[cid]['properties']['height']}",
            "codec": cams[cid]["codec"],
            "frames_sampled": frames,
            "plate_detections": detections,
            "valid_format_reads": raw_valid,
            "plate_yield": round(raw_valid / frames, 4) if frames else 0.0,
            "voted_plates": sorted(found),
            "voted_plate": voted.plate.canonical if voted else None,
            "voted_confidence": round(voted.confidence, 3) if voted else None,
            "votes": voted.votes if voted else 0,
            "explain": voted.explain() if voted else "no corroborated read",
            "expected_plates": sorted(expected),
            "correct": bool(found & expected),
            "false_positives": sorted(found - expected),
            "missed": sorted(expected - found),
            "recall": round(len(found & expected) / max(1, len(expected)), 3),
            "ms_per_frame": round(1000 * elapsed / max(1, frames), 1),
            "rejections": voter.stats(),
        }
        r = results[cid]
        got = ",".join(sorted(found)) or "—"
        print(f"{cid:<9}{r['department'][:15]:<16}{r['resolution']:<11}"
              f"{frames:>5}{detections:>5}{raw_valid:>5}{r['recall']:>7.2f}  "
              f"{got:<34}{r['ms_per_frame']:>7.1f}")
        if r["false_positives"]:
            print(f"{'':<9}  FALSE POSITIVES: {r['false_positives']}")

    # -- summary ----------------------------------------------------------- #
    anpr_viable = [c for c, r in results.items() if r["recall"] >= 0.5]
    declined = [c for c, r in results.items() if not r["voted_plates"]]
    correct = [c for c, r in results.items() if r["correct"]]

    print("\nSUMMARY")
    print(f"  cameras evaluated            : {len(results)}")
    print(f"  cameras with a voted plate   : {len(results) - len(declined)}")
    print(f"  voted plate matched truth    : {len(correct)}")
    print(f"  cameras the system declined  : {len(declined)}  {declined}")
    print(f"  ANPR-viable (recall >= 0.50) : {len(anpr_viable)}  {anpr_viable}")
    print("\n  Declining is a correct outcome on a camera that cannot support ANPR.")
    print("  A false read on such a camera would be worse than no read.")

    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(
        {"engine": engine.version, "sampling_fps": args.fps, "per_camera": results},
        indent=2))
    print(f"\n  machine-readable: {out.relative_to(ROOT)}")

    # Two independent conditions. "No wrong plates" alone is not a pass: a
    # pipeline that detects nothing at all satisfies it trivially, and an earlier
    # version of this harness reported PASS on exactly that collapse.
    wrong = [c for c, r in results.items() if r["false_positives"]]
    expected_readable = [c for c, r in results.items()
                         if r["expected_plates"] and c != "C-033"]
    produced = [c for c in expected_readable if results[c]["voted_plates"]]
    coverage = len(produced) / max(1, len(expected_readable))

    checks = [
        ("no camera published an incorrect plate", not wrong),
        (f"ANPR-viable cameras produced a read ({len(produced)}/{len(expected_readable)})",
         coverage >= 0.8),
        ("the degraded camera (C-033) declined rather than guessing",
         not results.get("C-033", {}).get("voted_plates")),
    ]
    print()
    ok = True
    for name, passed in checks:
        print(f"  [{'PASS' if passed else 'FAIL'}] {name}")
        ok = ok and passed
    if wrong:
        print(f"        wrong plates on: {wrong}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
